import { afterEach, describe, expect, test, vi } from 'vitest';
import { analyticsOptedOut, startAnalytics } from './analytics-init.js';
import { isQuietPath, recorderLoaded } from './utils/quietPages.js';

const ID = '123e4567-e89b-42d3-a456-426614174000';

function configuredDocument() {
  document.head.innerHTML = `<meta name="canquery-analytics-site" content="${ID}">`;
  return document;
}

afterEach(() => {
  document.head.innerHTML = '';
  vi.restoreAllMocks();
});

describe('analytics bootstrap privacy signals', () => {
  test.each([
    [{ doNotTrack: '1' }, {}],
    [{ globalPrivacyControl: true }, {}],
    [{}, { doNotTrack: 'yes' }],
  ])('does not start when a browser opt-out is active', (nav, win) => {
    const doc = configuredDocument();
    expect(analyticsOptedOut(nav, win)).toBe(true);
    expect(startAnalytics(doc, nav, win)).toBe(false);
    expect(doc.querySelector('script[src="/metrics.js"]')).toBeNull();
  });

  test('loads the same-origin tracker, then the heatmap recorder', () => {
    const doc = configuredDocument();
    expect(startAnalytics(doc, {}, {})).toBe(true);
    const tracker = doc.querySelector('script[src="/metrics.js"]');
    expect(tracker.dataset.websiteId).toBe(ID);
    expect(tracker.dataset.performance).toBe('false');
    expect(doc.querySelector('script[src="/heatmaps.js"]')).toBeNull();
    tracker.dispatchEvent(new Event('load'));
    const recorder = doc.querySelector('script[src="/heatmaps.js"]');
    expect(recorder).not.toBeNull();
    expect(recorder.dataset.websiteId).toBe(ID);
  });

  test('marks the document once the recorder is in it', () => {
    const doc = configuredDocument();
    const win = { location: { pathname: '/datasets' } };
    expect(startAnalytics(doc, {}, win)).toBe(true);
    expect(recorderLoaded(win)).toBe(false);
    doc.querySelector('script[src="/metrics.js"]').dispatchEvent(new Event('load'));
    expect(doc.querySelector('script[src="/heatmaps.js"]')).not.toBeNull();
    expect(recorderLoaded(win)).toBe(true);
  });

  test.each(['/oas', '/oas/table-3', '/fr/sv', '/fr/sv/tableau-5', '/OAS/'])(
    'a document that opens on %s gets the tracker and never the heatmap recorder', (pathname) => {
      const doc = configuredDocument();
      const win = { location: { pathname } };
      expect(startAnalytics(doc, {}, win)).toBe(true);
      const tracker = doc.querySelector('script[src="/metrics.js"]');
      expect(tracker).not.toBeNull();
      tracker.dispatchEvent(new Event('load'));
      expect(doc.querySelector('script[src="/heatmaps.js"]')).toBeNull();
      expect(recorderLoaded(win)).toBe(false);
    });

  test.each(['/oasis', '/lmia', '/blog/guaranteed-income-supplement-amounts', '/datasets/dfa4daf1-669e-4514-82cd-982f27707ed0', '/fr/svp'])(
    'a document that opens on %s gets the recorder as before', (pathname) => {
      const doc = configuredDocument();
      expect(isQuietPath(pathname)).toBe(false);
      startAnalytics(doc, {}, { location: { pathname } });
      doc.querySelector('script[src="/metrics.js"]').dispatchEvent(new Event('load'));
      expect(doc.querySelector('script[src="/heatmaps.js"]')).not.toBeNull();
    });

  test('accepts the UUIDv7 website ids generated by the analytics service', () => {
    const id = '01a02c60-cd0a-77f4-8680-7e9e317534a1';
    document.head.innerHTML = `<meta name="canquery-analytics-site" content="${id}">`;
    expect(startAnalytics(document, {}, {})).toBe(true);
    expect(document.querySelector('script[src="/metrics.js"]')?.dataset.websiteId).toBe(id);
  });

  test('does nothing without a valid server-injected website id', () => {
    document.head.innerHTML = '<meta name="canquery-analytics-site" content="not-an-id">';
    expect(startAnalytics(document, {}, {})).toBe(false);
  });
});
