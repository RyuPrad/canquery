// The hosted service adds its own strings and its wording for shared ones.
const HOSTED_STRINGS = hostedPart(import.meta.glob('./enterprise/strings.js', { eager: true }), { en: {}, fr: {} });
Object.assign(STRINGS.en, HOSTED_STRINGS.en);
Object.assign(STRINGS.fr, HOSTED_STRINGS.fr);

const lookup = (lang, key) => {
  const table = STRINGS[lang] || STRINGS.en;
  return table[key] !== undefined ? table[key] : (STRINGS.en[key] !== undefined ? STRINGS.en[key] : key);
};

// Default value keeps unwrapped components (and existing tests) in English.
const LangContext = createContext({ lang: 'en', setLang: () => {}, t: (key) => lookup('en', key) });

export function LangProvider({ children }) {
  const [blogTranslations, setBlogTranslations] = useState(null);
  const [lang, setLangState] = useState(() => {
    if (/^\/fr\/blog(?:\/|$)/.test(window.location.pathname)) return 'fr';
    if (/^\/blog(?:\/|$)/.test(window.location.pathname)) return 'en';
    try {
      return localStorage.getItem('cq-lang') === 'fr' ? 'fr' : 'en';
    } catch {
      return 'en';
    }
  });
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const setLang = useCallback((next) => {
    setLangState(next);
    try {
      localStorage.setItem('cq-lang', next);
    } catch {
      // private mode - language just won't persist
    }
  }, []);
  const t = useCallback((key) => lookup(lang, key), [lang]);
  return <LangContext.Provider value={{ lang, setLang, t, blogTranslations, setBlogTranslations }}>{children}</LangContext.Provider>;
}

export function useLang() {
  return useContext(LangContext);
}
